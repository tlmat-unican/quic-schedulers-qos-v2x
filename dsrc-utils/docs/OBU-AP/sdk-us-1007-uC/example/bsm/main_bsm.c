void craton_user_init(void)
{
	int ret;
	pthread_t thread_rx_bsm;
	pthread_t thread_tx_bsm;
	uint16_t c_serv_index, w_serv_index;
	wme_channel_info_t cs_info;
	wme_wsm_info_t ws_info;


	printf("This is a BSM Tx/Rx example, which sends BSMs periodically and receive BSMs.\n");

	linux_api_init();
	wave_init();
	gps_init();
	sec_hsm_init();
	dot3_init();


	/* Register to WME(1609.3) and configure the channel to 172 */
	ret = wme_init(&handle);
	if (ret != 0) {
		printf("wme_init: %d\n", ret);
		abort();
	}

	memset(&cs_info, 0, sizeof(cs_info));
	cs_info.service_priority = 1;
	cs_info.radio_number = RADIO_0;
	cs_info.channel_number = 172;
	cs_info.time_slot = TIME_SLOT_BOTH;
	ret = wme_channel_serv_create(&handle, &c_serv_index, &cs_info);
	if (ret != 0) {
		printf("wme_channel_serv_create: %d\n", ret);
		abort();
	}	

	memset(&ws_info, 0, sizeof(ws_info));
	ws_info.psid = 32;
	ret = wme_wsm_serv_create(&handle, &w_serv_index, &ws_info);
	if (ret != 0) {
		printf("wme_wsm_serv_create: %d\n", ret);
		abort();
	}	

	/* Note: The default stack size of ThreadX's pthread is 4K */
	ret = pthread_create(&thread_tx_bsm, NULL, bsm_tx_handler, NULL);
	if (ret != 0) {
		printf("pthread_create for BSM Tx failure\n");
		abort();
	}

	ret = pthread_create(&thread_rx_bsm, NULL, bsm_rx_handler, NULL);
	if (ret != 0) {
		printf("pthread_create for BSM Rx failure\n");
		abort();
	}

	return;
}

